const express = require("express");

const {
  getVolunteers,
  getVolunteer,
  createVolunteer,
  updateVolunteer,
  deleteVolunteer,
} = require("../controllers/volunteerController");


const router = express.Router();


/*
|--------------------------------------------------------------------------
| GET ALL VOLUNTEERS
|--------------------------------------------------------------------------
| GET /api/volunteers
|--------------------------------------------------------------------------
*/

router.get(
  "/",
  getVolunteers
);


/*
|--------------------------------------------------------------------------
| GET SINGLE VOLUNTEER
|--------------------------------------------------------------------------
| GET /api/volunteers/:id
|--------------------------------------------------------------------------
*/

router.get(
  "/:id",
  getVolunteer
);


/*
|--------------------------------------------------------------------------
| CREATE VOLUNTEER
|--------------------------------------------------------------------------
| POST /api/volunteers
|--------------------------------------------------------------------------
*/

router.post(
  "/",
  createVolunteer
);


/*
|--------------------------------------------------------------------------
| UPDATE VOLUNTEER
|--------------------------------------------------------------------------
| PUT /api/volunteers/:id
|--------------------------------------------------------------------------
*/

router.put(
  "/:id",
  updateVolunteer
);


/*
|--------------------------------------------------------------------------
| DELETE VOLUNTEER
|--------------------------------------------------------------------------
| DELETE /api/volunteers/:id
|--------------------------------------------------------------------------
*/

router.delete(
  "/:id",
  deleteVolunteer
);


module.exports = router;